package fsx

import (
	"os"
	"testing"

	"github.com/stretchr/testify/suite"
)

// ZIPSuite defines the test suite.
type ZIPSuite struct {
	suite.Suite
	createdFiles []string // Records files generated during tests for cleanup.
}

// TestZIPSuite starts the test suite.
func TestZIPSuite(t *testing.T) {
	suite.Run(t, new(ZIPSuite))
}

// SetupTest runs before each test case.
func (s *ZIPSuite) SetupTest() {
	s.createdFiles = nil
}

// TearDownTest runs after each test case and removes artifacts generated by the test.
func (s *ZIPSuite) TearDownTest() {
	for _, f := range s.createdFiles {
		if err := os.Remove(f); err != nil && !os.IsNotExist(err) {
			s.T().Logf("failed to remove %s: %v", f, err)
		}
	}
	s.createdFiles = nil
}

// TestCreateZIPFileWithFilename is a table-driven test.
func (s *ZIPSuite) TestCreateZIPFileWithFilename() {
	grids := []struct {
		source   string
		expected string
	}{
		{
			source:   "./test",
			expected: "test.zip",
		},
		{
			source:   "./zip.go",
			expected: "zip.zip",
		},
	}

	for _, grid := range grids {
		actual, err := CreateZIPFileWithFilename(grid.source)
		s.Require().NoError(err)
		s.Equal(grid.expected, actual)

		// Record the generated file so TearDownTest can clean it up.
		s.createdFiles = append(s.createdFiles, actual)
	}
}
